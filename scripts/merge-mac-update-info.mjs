// Merge per-arch macOS update manifests into the single latest-mac.yml.
//
// Unlike Linux (latest-linux.yml / latest-linux-arm64.yml), electron-builder
// always names the macOS update manifest latest-mac.yml regardless of arch
// (see app-builder-lib publish/updateInfoBuilder getArchPrefixForUpdateFile:
// arch suffix only applies to LINUX). So the two release jobs (macos-x64 /
// macos-arm64) publishing with `--publish always` would each overwrite the
// other's manifest, and the arch that lost the race would never receive
// in-app updates (MacUpdater filters files by "arm64" in the URL).
//
// Each mac job therefore uploads its own manifest as latest-mac-x64.yml /
// latest-mac-arm64.yml; this script merges them back into one latest-mac.yml
// listing both archs' dmg + zip files, and the workflow re-uploads it.
//
//   node scripts/merge-mac-update-info.mjs latest-mac-x64.yml latest-mac-arm64.yml latest-mac.yml

import { readFileSync, writeFileSync } from 'node:fs';

const [x64File, arm64File, outFile] = process.argv.slice(2);
if (!x64File || !arm64File || !outFile) {
  console.error(
    'Usage: node scripts/merge-mac-update-info.mjs <latest-mac-x64.yml> <latest-mac-arm64.yml> <out.yml>',
  );
  process.exit(1);
}

/**
 * Minimal YAML reader for electron-builder's update-info schema:
 *
 *   version: 0.1.0
 *   files:
 *     - url: weQ-0.1.0-mac-x64.zip
 *       sha512: <base64>
 *       size: 12345
 *   path: weQ-0.1.0-mac-x64.zip
 *   sha512: <base64>
 *   releaseDate: '2026-08-27T...'
 *
 * Anything beyond this shape (e.g. releaseNotes) is intentionally not merged;
 * the schema is generated by electron-builder and stable for this project.
 */
function parseYml(text) {
  /** @type {Map<string, string>} */
  const top = new Map();
  /** @type {Array<Record<string, string>>} */
  const files = [];
  /** @type {Record<string, string> | null} */
  let current = null;

  for (const line of text.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;

    const indent = line.length - line.trimStart().length;
    const urlMatch = /^-\s+url:\s*(.+)$/.exec(trimmed);
    if (urlMatch) {
      if (current) files.push(current);
      current = { url: urlMatch[1].trim() };
      continue;
    }

    const kv = /^([A-Za-z0-9_.-]+):(?:\s*(.*))?$/.exec(trimmed);
    if (!kv) continue; // unknown line — ignore (shouldn't happen for this schema)

    const [, key, rawValue] = kv;
    const value = rawValue == null ? '' : rawValue.trim();
    if (indent === 0) {
      if (current) {
        files.push(current);
        current = null;
      }
      if (key !== 'files') top.set(key, value);
    } else if (current) {
      current[key] = value;
    }
  }
  if (current) files.push(current);

  return { top, files };
}

const x64 = parseYml(readFileSync(x64File, 'utf8'));
const arm64 = parseYml(readFileSync(arm64File, 'utf8'));

const versionX64 = x64.top.get('version');
const versionArm64 = arm64.top.get('version');
if (!versionX64 || versionX64 !== versionArm64) {
  console.error(`version mismatch: "${versionX64}" (x64) vs "${versionArm64}" (arm64)`);
  process.exit(1);
}

// Dedupe by URL, keeping x64 entries first (both archs must be listed so
// MacUpdater can pick by architecture).
const byUrl = new Map();
for (const file of [...x64.files, ...arm64.files]) byUrl.set(file.url, file);
const mergedFiles = [...byUrl.values()];

const top = new Map(x64.top);
// Legacy `path` / `sha512` (electron-updater 1.x) — keep the default arch's.
for (const key of ['path', 'sha512']) {
  if (!top.has(key)) {
    const fallback = arm64.top.get(key);
    if (fallback) top.set(key, fallback);
  }
}
// Keep the newest releaseDate when both files carry one.
if (x64.top.has('releaseDate') && arm64.top.has('releaseDate')) {
  const strip = (v) => v.replace(/^['"]|['"]$/g, '');
  if (strip(arm64.top.get('releaseDate')) > strip(x64.top.get('releaseDate'))) {
    top.set('releaseDate', arm64.top.get('releaseDate'));
  }
}

const lines = [];
for (const [key, value] of top) {
  if (key === 'files') continue;
  lines.push(`${key}: ${value}`);
}
lines.push('files:');
for (const file of mergedFiles) {
  lines.push(`  - url: ${file.url}`);
  for (const [key, value] of Object.entries(file)) {
    if (key === 'url') continue;
    lines.push(`    ${key}: ${value}`);
  }
}
lines.push('');

writeFileSync(outFile, `${lines.join('\n')}\n`);
console.log(
  `merged ${x64.files.length} (x64) + ${arm64.files.length} (arm64) entries -> ${outFile} (${mergedFiles.length} unique)`,
);
