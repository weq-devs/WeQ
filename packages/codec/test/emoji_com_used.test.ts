test('decodes a real emoji_com_used blob', () => {
  const proto = new ProtoMsg(EmojiComUsed);
  const decoded = proto.decode(Uint8Array.from(Buffer.from(HEX, 'hex')));

  expect(Number(decoded.info?.updatedAt)).toBe(1790280957);
  const items = decoded.info?.items ?? [];
  expect(items).toHaveLength(30);

  // 首条：小黄脸 /斜眼笑（faceId 178），图片表情。
  expect(Number(items[0]?.faceId)).toBe(178);
  expect(Number(items[0]?.sourceType)).toBe(11);
  expect(Number(items[0]?.unicode ?? 0)).toBe(0);
  expect(Number(items[0]?.usedAt)).toBe(1790280958008);

  // 一条 unicode 字符表情：faceId 0 + 字形存在 80775。
  const unicode = items.find((it) => Number(it.unicode) === 1);
  expect(unicode).toBeTruthy();
  expect(new TextDecoder().decode(unicode?.extra)).toBe('👎');

  // 图片表情的 80775 偶尔带 faceId 字符串（314）。
  const withIdString = items.find((it) => Number(it.faceId) === 314);
  expect(new TextDecoder().decode(withIdString?.extra)).toBe('314');
});

test('re-encodes the decoded blob without losing entries', () => {
  const proto = new ProtoMsg(EmojiComUsed);
  const decoded = proto.decode(Uint8Array.from(Buffer.from(HEX, 'hex')));
  const again = proto.decode(proto.encode(decoded));
  expect(again.info?.items).toHaveLength(30);
  expect(Number(again.info?.updatedAt)).toBe(1790280957);
  expect(Number(again.info?.items?.[0]?.faceId)).toBe(178);
});
