/** native 发 OIDB 时使用的 wire 命令串（小写十六进制，与 native 实现一致）。 */
export function oidbWireCommand(command: number, subCommand: number): string {
  return `OidbSvcTrpcTcp.0x${command.toString(16)}_${subCommand}`;
}

/** 按 LagrangeV2 白名单判断某个 wire 命令是否需要 `SecSign/SecToken/SecExtra`。 */
export function commandNeedsSign(wireCommand: string): boolean {
  return SIGN_WHITELIST.has(wireCommand.toLowerCase());
}

/** 便捷封装：OIDB `(command, subCommand)` 是否需要签名。 */
export function oidbNeedsSign(command: number, subCommand: number): boolean {
  return commandNeedsSign(oidbWireCommand(command, subCommand));
}
